/* ============================================================
   第4章 递归 —— 调用栈与堆栈（教学重点）
   ------------------------------------------------------------
   用 cdbg 单步进入 fact() 后可以观察到：
     · 调用栈里出现多个 fact() 帧，每一层的 n 都住在栈上不同的位置
     · 每一层的 r（返回值变量）也是各自独立的
     · 栈从高地址向低地址增长：越深的层，地址反而越小
     · 递归结束后，栈帧逐层弹出，空间被回收
   ============================================================ */

#include <stdio.h>

long fact(int n)
{
    int r = 1;
    if (n > 1) {
        r = n * fact(n - 1);   /* 递归调用：调用自己 */
    }
    return r;
}

/* 斐波那契：递归树更宽，适合看「多个同层兄弟帧」 */
long fib(int n)
{
    if (n < 2)
        return n;
    return fib(n - 1) + fib(n - 2);
}

int main(void)
{
    int depth = 5;
    long f, g;

    f = fact(depth);
    g = fib(6);

    printf("fact(%d) = %ld\n", depth, f);
    printf("fib(6)   = %ld\n", g);
    return 0;
}
