#: 全量词库（已过滤）。顺序与原表一致，方便出事时对照。
LINES: Sequence[str] = _CURATED


def lines() -> List[str]:
    """全部可用文案。"""
    return list(LINES)


def fill(line: str, file_name: str = "") -> str:
    """把词库里的占位符换掉。

    上游是给 LLM 状态条用的，带 `{file_name}` / `{provider}` 两种占位符。
    不换的话界面上会明晃晃地显示一个花括号，看着像我们自己的 bug。
    `{provider}` 在这里没有对应的东西，就填「GDB」—— 调试器本来也就是
    那个「被进攻的对象」。
    """
    return (
        line.replace("{file_name}", file_name or "这段代码")
        .replace("{provider}", "GDB")
    )


def sample(n: int = 1, exclude: str = "", file_name: str = "") -> List[str]:
    """随机取 n 条，互不重复；给了 exclude 就避开它 —— 换一条时别连着同一条。"""
    pool = [s for s in LINES if fill(s, file_name) != exclude] or list(LINES)
    return [fill(s, file_name) for s in random.sample(pool, min(n, len(pool)))]


def one(exclude: str = "", file_name: str = "") -> str:
    """随机取一条。"""
    picked = sample(1, exclude=exclude, file_name=file_name)
    return picked[0] if picked else ""
